-- Config tables (geo_areas, shipping_zones, courier_coverage, rate_cards) have no tenant key: public configuration, no personal data.
-- outlet_app may only read them (writes are admin/worker work through a later migration or seed job).
-- store_shipping_settings is store-owned (app.enable_store_rls), seller writes only. The shopper quote path reads the public projection
-- shipping_public_store_settings (same pattern as cart_store_thresholds / catalog_public_*): keyed by store_ref, no RLS, no personal data,
-- written by the service in the SAME transaction as the settings row; DELETE revoked.
-- Deviations: rate_cards is priced per weight band (from < w <= to, grams) and carries the courier step and volumetric divisor (spec 3, V33);
-- geo_areas ids are gen_random_uuid() in the seed (UUIDv7 is generated by the application for runtime rows).
-- courier_codes and shipments are not built here: P1-07a is quote-only. No courier is contracted (owner decision, V33/V43).
-- Governorate codes follow ISO 3166-2:EG except Cairo = CAI (matches sellers.governorate_code).

CREATE TABLE geo_areas (
  id                 uuid PRIMARY KEY,
  market_id          text NOT NULL CHECK (length(market_id) > 0),
  parent_id          uuid REFERENCES geo_areas (id),
  level              text NOT NULL CHECK (level IN ('governorate', 'city', 'district')),
  code               text NOT NULL CHECK (length(code) > 0),
  name_ar            text NOT NULL,
  name_en            text,
  courier_codes      jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(courier_codes) = 'object'),
  shipping_zone_code text,
  active             boolean NOT NULL DEFAULT true,
  created_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (market_id, code),
  CHECK ((level = 'governorate') = (parent_id IS NULL))
);
CREATE INDEX geo_areas_picker_idx ON geo_areas (market_id, parent_id, level);

CREATE TABLE shipping_zones (
  market_id  text NOT NULL,
  zone_code  text NOT NULL,
  kind       text NOT NULL CHECK (kind IN ('domestic', 'international')),
  name_ar    text NOT NULL,
  name_en    text NOT NULL,
  countries  text[] NOT NULL DEFAULT '{}',
  PRIMARY KEY (market_id, zone_code)
);

CREATE TABLE courier_coverage (
  id            uuid PRIMARY KEY,
  market_id     text NOT NULL,
  courier       text NOT NULL CHECK (length(courier) > 0),
  geo_area_id   uuid NOT NULL REFERENCES geo_areas (id),
  service_level text NOT NULL CHECK (length(service_level) > 0),
  sla_days_p80  smallint NOT NULL CHECK (sla_days_p80 BETWEEN 1 AND 60),
  cod_supported boolean NOT NULL DEFAULT false,
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (courier, geo_area_id, service_level)
);
CREATE INDEX courier_coverage_lookup_idx ON courier_coverage (market_id, geo_area_id) WHERE active;

CREATE TABLE rate_cards (
  id                 uuid PRIMARY KEY,
  market_id          text NOT NULL,
  courier            text NOT NULL,
  service_level      text NOT NULL,
  zone_code          text NOT NULL,
  weight_from_g      int NOT NULL CHECK (weight_from_g >= 0),
  weight_to_g        int NOT NULL,
  weight_step_g      int NOT NULL DEFAULT 500 CHECK (weight_step_g > 0),
  volumetric_divisor int NOT NULL DEFAULT 5000 CHECK (volumetric_divisor > 0),
  price_minor        bigint NOT NULL CHECK (price_minor >= 0),
  currency           char(3) NOT NULL,
  version            int NOT NULL DEFAULT 1 CHECK (version >= 1),
  valid_from         timestamptz NOT NULL,
  valid_to           timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (market_id, zone_code) REFERENCES shipping_zones (market_id, zone_code),
  CHECK (weight_to_g > weight_from_g),
  CHECK (valid_to IS NULL OR valid_to > valid_from),
  UNIQUE (courier, service_level, market_id, zone_code, weight_from_g, valid_from)
);
-- Quote join: coverage row -> rate band by (market, courier, service, zone) within the validity window.
CREATE INDEX rate_cards_quote_idx ON rate_cards (market_id, courier, service_level, zone_code, valid_from DESC, weight_from_g);

CREATE TABLE store_shipping_settings (
  store_id                     uuid PRIMARY KEY REFERENCES stores (id),
  market_id                    text NOT NULL,
  free_threshold_override_minor bigint CHECK (free_threshold_override_minor IS NULL OR free_threshold_override_minor >= 0),
  allowed_couriers             text[] NOT NULL DEFAULT '{}',
  handling_days                smallint NOT NULL DEFAULT 1 CHECK (handling_days BETWEEN 0 AND 14),
  updated_by                   uuid,
  updated_at                   timestamptz NOT NULL DEFAULT now()
);
