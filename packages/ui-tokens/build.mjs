// Emits dist/tokens.css (CSS custom properties, light + dark) and dist/tokens.ts from tokens.json.
// tokens.json stays the single source. Run: node build.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

const get = (path) => path.split(".").reduce((o, k) => o?.[k], tokens);
function resolve(value) {
  let v = value;
  let guard = 0;
  while (typeof v === "string" && v.startsWith("{")) {
    const next = get(v.slice(1, -1));
    if (next?.$value === undefined || ++guard > 10) throw new Error(`unresolvable token reference ${v}`);
    v = next.$value;
  }
  return v;
}
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Flatten a subtree into [dotted path, resolved value, $type]. */
function leaves(node, path = []) {
  if (node && typeof node === "object" && "$value" in node) return [[path, resolve(node.$value), node.$type]];
  return Object.entries(node ?? {})
    .filter(([k]) => !k.startsWith("$"))
    .flatMap(([k, v]) => leaves(v, [...path, k]));
}
function cssValue(value, type) {
  if (type === "fontFamily") return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (type === "cubicBezier") return `cubic-bezier(${value.join(", ")})`;
  return String(value);
}
const varName = (prefix, path) => `--${[prefix, ...path].map(kebab).join("-")}`;
const decl = (name, value) => `  ${name}: ${value};`;

const themeVars = (theme) => leaves(tokens.theme[theme]).map(([p, v, t]) => [varName("color", p), cssValue(v, t), p.join("."), v]);
const scaleGroups = ["font", "space", "radius", "elevation", "motion"];
const scaleVars = scaleGroups.flatMap((g) =>
  leaves(tokens[g]).filter(([p]) => !(g === "motion" && p[0] === "reduced")).map(([p, v, t]) => [varName(g, p), cssValue(v, t)]),
);
const reducedVars = leaves(tokens.motion.reduced).map(([p, v]) => [`--motion-reduced-${p.map(kebab).join("-")}`, String(v)]);

const block = (selector, rows, extra = []) => `${selector} {\n${[...rows.map(([n, v]) => decl(n, v)), ...extra].join("\n")}\n}`;
const light = themeVars("light");
const dark = themeVars("dark");

const css = [
  "/* Generated by packages/ui-tokens/build.mjs from tokens.json. Do not edit. */",
  block(':root,\n[data-theme="light"]', [...scaleVars, ...reducedVars, ...light], ["  color-scheme: light;"]),
  `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, ["  color-scheme: dark;"])
    .split("\n").map((l) => (l ? `  ${l}` : l)).join("\n")}\n}`,
  block('[data-theme="dark"]', dark, ["  color-scheme: dark;"]),
  "@media (prefers-reduced-motion: reduce) {\n  :root {\n    --motion-duration-fast: var(--motion-reduced-duration);\n    --motion-duration-base: var(--motion-reduced-duration);\n    --motion-duration-slow: var(--motion-reduced-duration);\n  }\n}",
  "",
].join("\n");

const obj = (rows) => Object.fromEntries(rows);
const ts = `// Generated by packages/ui-tokens/build.mjs from tokens.json. Do not edit.
export const tokens = ${JSON.stringify(
  {
    themes: {
      light: obj(themeVars("light").map(([, , p, v]) => [p, v])),
      dark: obj(themeVars("dark").map(([, , p, v]) => [p, v])),
    },
    breakpoint: obj(leaves(tokens.breakpoint).map(([p, v]) => [p.join("."), v])),
    cssVars: { light: obj(light.map(([n, , p]) => [p, n])), scale: obj(scaleVars.map(([n, v]) => [n, v])) },
  },
  null,
  2,
)} as const;

export type ThemeName = keyof typeof tokens.themes;
export type ThemeTokenName = keyof (typeof tokens.themes)["light"];
`;

mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist/tokens.css"), css);
writeFileSync(join(here, "dist/tokens.ts"), ts);
console.log(`ui-tokens: wrote dist/tokens.css (${css.length} bytes) and dist/tokens.ts`);
