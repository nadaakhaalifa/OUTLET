// Generates typed declarations (X.module.css.d.ts) with the real class names of each CSS module.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const srcDir = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".module.css"))) {
  const css = readFileSync(join(srcDir, file), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const names = new Set();
  for (const m of css.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)) {
    if (/^\d/.test(m[1])) continue;
    names.add(m[1]);
  }
  const body = [...names].sort().map((n) => (/^[A-Za-z_$][\w$]*$/.test(n) ? n : JSON.stringify(n))).map((n) => `  readonly ${n}: string;`).join("\n");
  writeFileSync(join(srcDir, `${file}.d.ts`), `// Generated by scripts/css-types.mjs. Do not edit.\ndeclare const classes: {\n${body}\n};\nexport default classes;\n`);
}
