import { analyticsEvents, ANALYTICS_EVENT_NAMES } from "./analytics-events";
import { z } from "zod";

function props(shape: z.ZodRawShape): string {
  return Object.entries(shape)
    .map(([k, s]) => `\`${k}${z.safeParse(s, undefined).success ? "?" : ""}\``)
    .join(", ");
}

/**
 * Renders docs/analytics/events.md from the catalog (spec section 26 path). Pure: callers write the file.
 * The registry check test fails when the committed file differs from this output.
 */
export function renderEventsDoc(): string {
  const rows = ANALYTICS_EVENT_NAMES.map((n) => {
    const d = analyticsEvents[n];
    const gate = d.purpose === "strictly_necessary" ? "strictly necessary (no consent)" : `consent: \`${d.purpose}\``;
    return `| \`${n}\` | ${d.version} | ${d.origin} | ${gate} | ${props(d.shape)} | ${d.owner} | ${d.specRef} |`;
  });
  return [
    "# Analytics events",
    "",
    "<!-- GENERATED by packages/analytics (renderEventsDoc). Do not edit by hand.",
    "     Regenerate: node packages/analytics/scripts/generate-events-doc.mjs -->",
    "",
    "Every property is P0 or P1, snake_case, flat. No phone, email, DOB, address, measurement or budget amount is ever a property; budget events carry bands only. See `event-taxonomy.md` for rules and domain events.",
    "",
    "| Event | Version | Origin | Gate | Properties (`?` optional) | Owner | Spec |",
    "|---|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}
