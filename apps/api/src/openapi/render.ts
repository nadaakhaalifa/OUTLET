import { stringify } from "yaml";
import type { RouteDef } from "../platform/route-registry.js";
import { buildOpenApi } from "./generate.js";

export const GENERATED_HEADER = "# GENERATED by pnpm --filter api openapi. Do not edit.\n";

/** Exact file content the CLI writes (the drift test compares it with the committed file). */
export const renderOpenApi = (routes: readonly RouteDef[]): string => `${GENERATED_HEADER}${stringify(buildOpenApi(routes), { lineWidth: 0 })}`;
