#!/usr/bin/env node
// Deterministic OpenAPI -> TypeScript client generator (master prompt T1).
//
// Reads docs/api/openapi.yaml (no network) and emits into packages/api-client/src/generated/:
//   schemas.ts     Zod schemas (snake_case wire shape) + inferred types for every components.schemas entry
//   operations.ts  one typed entry per operationId (method, path, params, input/output Zod) and the OutletClient interface
//
// Usage:
//   node tooling/api/generate-client.mjs           write the files
//   node tooling/api/generate-client.mjs --check   exit 1 when committed files differ from a fresh generation
//
// `generate(yamlText)` is exported for the drift test: it returns { relativePath: contents } in memory.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_SPEC = resolve(here, "../../docs/api/openapi.yaml");
export const DEFAULT_OUT = resolve(here, "../../packages/api-client/src/generated");

const METHODS = ["get", "put", "post", "delete", "patch"];
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const q = (s) => JSON.stringify(s);
const key = (k) => (IDENT.test(k) ? k : q(k));
const refName = (ref) => ref.split("/").pop();

function header(doc) {
  return [
    "// GENERATED by tooling/api/generate-client.mjs from docs/api/openapi.yaml. DO NOT EDIT.",
    `// Contract: ${doc.info?.title ?? "API"} ${doc.info?.version ?? ""}. Regenerate with: node tooling/api/generate-client.mjs`,
    "",
  ].join("\n");
}

class Gen {
  constructor(doc) {
    this.doc = doc;
    this.schemas = doc.components?.schemas ?? {};
    this.lazy = new Set(); // "From>To" edges that must be z.lazy
    this.order = [];
  }

  resolve(node) {
    let n = node;
    const seen = new Set();
    while (n && n.$ref) {
      if (seen.has(n.$ref)) throw new Error(`ref loop ${n.$ref}`);
      seen.add(n.$ref);
      const parts = n.$ref.replace(/^#\//, "").split("/");
      let cur = this.doc;
      for (const p of parts) cur = cur?.[p];
      if (cur === undefined) throw new Error(`unresolved ${n.$ref}`);
      n = cur;
    }
    return n;
  }

  /** Merge allOf members (resolving $refs) into a single object schema. */
  mergeAllOf(node) {
    const out = { type: "object", properties: {}, required: [], additionalProperties: undefined };
    let strict = true;
    for (const part of node.allOf) {
      let p = this.resolve(part);
      if (p.allOf) p = this.mergeAllOf(p);
      if (p.type !== "object" && p.properties === undefined) throw new Error("allOf of non-object is not supported");
      Object.assign(out.properties, p.properties ?? {});
      for (const r of p.required ?? []) if (!out.required.includes(r)) out.required.push(r);
      if (p.additionalProperties !== false) strict = false;
    }
    out.additionalProperties = strict ? false : true;
    return out;
  }

  collectRefs(node, acc) {
    if (Array.isArray(node)) node.forEach((x) => this.collectRefs(x, acc));
    else if (node && typeof node === "object") {
      if (typeof node.$ref === "string" && node.$ref.startsWith("#/components/schemas/")) acc.add(refName(node.$ref));
      for (const v of Object.values(node)) this.collectRefs(v, acc);
    }
  }

  topo() {
    const state = new Map();
    const visit = (name, from) => {
      const st = state.get(name);
      if (st === 2) return;
      if (st === 1) {
        this.lazy.add(`${from}>${name}`);
        return;
      }
      state.set(name, 1);
      const refs = new Set();
      this.collectRefs(this.schemas[name], refs);
      for (const r of [...refs].sort()) visit(r, name);
      state.set(name, 2);
      this.order.push(name);
    };
    for (const name of Object.keys(this.schemas)) visit(name, name);
  }

  expr(node, ctx) {
    if (node === true || node === undefined) return "z.unknown()";
    if (node.$ref) {
      const name = refName(node.$ref);
      if (!node.$ref.startsWith("#/components/schemas/")) throw new Error(`unsupported ref ${node.$ref}`);
      const target = `${ctx.prefix}${name}`;
      return this.lazy.has(`${ctx.current}>${name}`) ? `z.lazy(() => ${target})` : target;
    }
    if (node.allOf) return this.expr(this.mergeAllOf(node), ctx);
    if (node.oneOf || node.anyOf) {
      const variants = node.oneOf ?? node.anyOf;
      const nonNull = variants.filter((v) => !(v.type === "null" && Object.keys(v).length === 1));
      const hasNull = nonNull.length !== variants.length;
      let inner;
      if (nonNull.length === 1) inner = this.expr(nonNull[0], ctx);
      else {
        const disc = node.discriminator?.propertyName;
        const parts = nonNull.map((v) => this.expr(v, ctx));
        inner = disc ? `z.discriminatedUnion(${q(disc)}, [${parts.join(", ")}])` : `z.union([${parts.join(", ")}])`;
      }
      return hasNull ? `${inner}.nullable()` : inner;
    }
    if (node.const !== undefined) return `z.literal(${q(node.const)})`;
    let types = Array.isArray(node.type) ? node.type : node.type === undefined ? [] : [node.type];
    const nullable = types.includes("null");
    types = types.filter((t) => t !== "null");
    if (node.enum) {
      const vals = node.enum.filter((v) => v !== null);
      const base = vals.every((v) => typeof v === "string") ? `z.enum([${vals.map(q).join(", ")}])` : `z.union([${vals.map((v) => `z.literal(${q(v)})`).join(", ")}])`;
      return nullable || node.enum.includes(null) ? `${base}.nullable()` : base;
    }
    let e;
    const t = types[0] ?? (node.properties ? "object" : undefined);
    switch (t) {
      case "string": {
        const f = node.format;
        e =
          f === "uuid" ? "z.guid()" :
          f === "date-time" ? "z.iso.datetime({ offset: true })" :
          f === "date" ? "z.iso.date()" :
          f === "email" ? "z.email()" :
          f === "uri" ? "z.url()" :
          "z.string()";
        if (node.pattern !== undefined) e += `.regex(new RegExp(${q(node.pattern)}))`;
        if (node.minLength !== undefined) e += `.min(${node.minLength})`;
        if (node.maxLength !== undefined) e += `.max(${node.maxLength})`;
        break;
      }
      case "integer":
      case "number": {
        e = t === "integer" ? "z.number().int()" : "z.number()";
        if (node.minimum !== undefined) e += `.min(${node.minimum})`;
        if (node.maximum !== undefined) e += `.max(${node.maximum})`;
        break;
      }
      case "boolean":
        e = "z.boolean()";
        break;
      case "array": {
        e = `z.array(${this.expr(node.items, ctx)})`;
        if (node.minItems !== undefined) e += `.min(${node.minItems})`;
        if (node.maxItems !== undefined) e += `.max(${node.maxItems})`;
        break;
      }
      case "object": {
        const props = node.properties ?? {};
        const names = Object.keys(props);
        const ap = node.additionalProperties;
        if (names.length === 0) {
          e = ap && typeof ap === "object" ? `z.record(z.string(), ${this.expr(ap, ctx)})` : "z.record(z.string(), z.unknown())";
          break;
        }
        const req = new Set(node.required ?? []);
        const fields = names.map((n) => `${key(n)}: ${this.expr(props[n], ctx)}${req.has(n) ? "" : ".optional()"}`);
        e = `${ap === false ? "z.strictObject" : "z.looseObject"}({ ${fields.join(", ")} })`;
        break;
      }
      case undefined:
        e = "z.unknown()";
        break;
      default:
        throw new Error(`unsupported type ${t}`);
    }
    return nullable ? `${e}.nullable()` : e;
  }

  schemasFile() {
    this.topo();
    const lines = [header(this.doc), 'import { z } from "zod";', ""];
    for (const name of this.order) {
      const e = this.expr(this.schemas[name], { prefix: "", current: name });
      lines.push(`export const ${name} = ${e};`);
      lines.push(`export type ${name} = z.infer<typeof ${name}>;`);
    }
    return lines.join("\n") + "\n";
  }

  param(p) {
    return this.resolve(p);
  }

  operationsFile() {
    const ops = [];
    for (const [path, item] of Object.entries(this.doc.paths)) {
      for (const m of METHODS) {
        const op = item[m];
        if (!op) continue;
        if (!op.operationId) throw new Error(`${m} ${path} has no operationId`);
        ops.push({ path, method: m, op, shared: item.parameters ?? [] });
      }
    }
    ops.sort((a, b) => (a.op.operationId < b.op.operationId ? -1 : a.op.operationId > b.op.operationId ? 1 : 0));
    const ids = new Set();
    const ctx = { prefix: "S.", current: "" };
    const entries = [];
    const iface = [];
    for (const { path, method, op, shared } of ops) {
      const id = op.operationId;
      if (ids.has(id)) throw new Error(`duplicate operationId ${id}`);
      ids.add(id);
      const params = [...shared, ...(op.parameters ?? [])].map((p) => this.param(p));
      const pathP = params.filter((p) => p.in === "path");
      const queryP = params.filter((p) => p.in === "query");
      const headerP = params.filter((p) => p.in === "header");
      const idemP = headerP.find((p) => p.name.toLowerCase() === "idempotency-key");
      const otherHeaders = headerP.filter((p) => p !== idemP);
      const groups = [];
      const group = (name, list) => {
        if (list.length === 0) return;
        const required = list.some((p) => p.required === true || p.in === "path");
        const fields = list.map((p) => `${key(p.name)}: ${this.expr(p.schema, ctx)}${p.required === true || p.in === "path" ? "" : ".optional()"}`);
        groups.push({ name, required, code: `z.object({ ${fields.join(", ")} })` });
      };
      group("path", pathP);
      group("query", queryP);
      group("headers", otherHeaders);
      const rb = op.requestBody;
      if (rb) {
        const json = rb.content?.["application/json"];
        if (!json) throw new Error(`${id}: only application/json request bodies are supported`);
        groups.push({ name: "body", required: rb.required === true, code: this.expr(json.schema, ctx) });
      }
      const inputRequired = groups.some((g) => g.required);
      const inputCode = `z.object({ ${groups.map((g) => `${g.name}: ${g.code}${g.required ? "" : ".optional()"}`).join(", ")} })`;
      const okEntry = Object.entries(op.responses).find(([s]) => /^2\d\d$/.test(s));
      if (!okEntry) throw new Error(`${id}: no 2xx response`);
      const [okStatus, okRaw] = okEntry;
      const ok = this.resolve(okRaw);
      let kind = "empty";
      let outCode = "z.null()";
      if (ok.content?.["application/json"]) {
        kind = "json";
        outCode = this.expr(ok.content["application/json"].schema, ctx);
      } else if (ok.content) {
        kind = "binary";
        outCode = "z.instanceof(ArrayBuffer)";
      }
      const notModified = Object.keys(op.responses).includes("304");
      const security = [...new Set((op.security ?? []).flatMap((s) => Object.keys(s)))];
      const planned = op["x-status"] === "planned";
      const idem = idemP ? (idemP.required === true ? "required" : "optional") : "none";
      entries.push(
        `  ${key(id)}: {\n` +
          `    operationId: ${q(id)},\n    method: ${q(method.toUpperCase())},\n    path: ${q(path)},\n    tag: ${q(op.tags?.[0] ?? "")},\n` +
          `    security: ${q(security)} as readonly string[],\n    idempotency: ${q(idem)} as "none" | "optional" | "required",\n` +
          `    pathParams: ${q(pathP.map((p) => p.name))} as readonly string[],\n    queryParams: ${q(queryP.map((p) => p.name))} as readonly string[],\n    headerParams: ${q(otherHeaders.map((p) => p.name))} as readonly string[],\n` +
          `    planned: ${planned ? "true" : "false"},\n    hasBody: ${rb ? "true" : "false"},\n    successStatus: ${okStatus},\n    responseKind: ${q(kind)} as "json" | "empty" | "binary",\n    notModified: ${notModified},\n` +
          `    input: ${inputCode},\n    output: ${outCode},\n  },`,
      );
      // ADR-0050: a planned operation is a notImplemented stub. Same input and output types; the runtime never sends a request.
      const ret = planned ? `ApiResponse<OperationOutput<${q(id)}>> | ApiNotImplemented` : `ApiResponse<OperationOutput<${q(id)}>>`;
      iface.push(
        `  ${key(id)}(${inputRequired ? "input" : "input?"}: OperationInput<${q(id)}>, options?: CallOptions): Promise<${ret}>;`,
      );
    }
    return [
      header(this.doc),
      'import { z } from "zod";',
      'import type { ApiNotImplemented, ApiResponse, CallOptions } from "../runtime/types";',
      'import * as S from "./schemas";',
      "",
      "export const operations = {",
      entries.join("\n"),
      "} as const;",
      "",
      "export type Operations = typeof operations;",
      "export type OperationId = keyof Operations;",
      'export type OperationInput<K extends OperationId> = z.input<Operations[K]["input"]>;',
      'export type OperationOutput<K extends OperationId> = z.output<Operations[K]["output"]>;',
      "",
      "export interface OutletClient {",
      iface.join("\n"),
      "}",
      "",
    ].join("\n");
  }
}

/** Pure: YAML text in, { "schemas.ts": ..., "operations.ts": ... } out. Deterministic. */
export function generate(yamlText) {
  const doc = parse(yamlText);
  const g = new Gen(doc);
  const ops = g.operationsFile; // bind order: schemas first so lazy edges are known
  const schemas = g.schemasFile();
  return { "schemas.ts": schemas, "operations.ts": ops.call(g) };
}

function main() {
  const check = process.argv.includes("--check");
  const spec = readFileSync(DEFAULT_SPEC, "utf8");
  const files = generate(spec);
  let drift = 0;
  if (!check) mkdirSync(DEFAULT_OUT, { recursive: true });
  for (const [name, contents] of Object.entries(files)) {
    const p = join(DEFAULT_OUT, name);
    if (check) {
      if (!existsSync(p) || readFileSync(p, "utf8") !== contents) {
        console.error(`api-client: ${name} is stale; run node tooling/api/generate-client.mjs`);
        drift++;
      }
    } else {
      writeFileSync(p, contents);
      console.log(`wrote ${p} (${contents.length} bytes)`);
    }
  }
  if (drift > 0) process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
