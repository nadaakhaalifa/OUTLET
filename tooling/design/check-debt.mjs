#!/usr/bin/env node
// Design debt gate: runs eslint in strict mode (baseline exemptions off) over mobile + ui-native,
// groups violations per file and rule code, and compares with tooling/design/debt-baseline.json.
//   node tooling/design/check-debt.mjs            fail when any file/rule count grows or a new file appears
//   node tooling/design/check-debt.mjs --update   write the baseline, ONLY if nothing grew (shrinks the debt)
//   node tooling/design/check-debt.mjs --init     write the baseline unconditionally (first run only)
// Also regenerates docs/plan/design-debt.md.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { BASELINE_PATH, codeOf } from "./rules.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const arg = process.argv[2];

const eslintBin = join(root, "node_modules/.bin/eslint");
const r = spawnSync(eslintBin, ["--format", "json", "apps/mobile/src", "packages/ui-native/src", "packages/ui-web/src", "apps/admin-web/src/app/spike"], {
  cwd: root, env: { ...process.env, DESIGN_STRICT: "1" }, encoding: "utf8", maxBuffer: 256 * 1024 * 1024,
});
if (!r.stdout) { console.error(r.stderr || "eslint produced no output"); process.exit(2); }
const results = JSON.parse(r.stdout);

/** @type {Record<string, Record<string, number>>} */
const current = {};
for (const f of results) {
  for (const m of f.messages) {
    const code = codeOf(m.message);
    if (!code) continue;
    const file = relative(root, f.filePath);
    ((current[file] ??= {})[code] ??= 0);
    current[file][code] += 1;
  }
}
const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => [k, Object.fromEntries(Object.entries(v).sort(([a], [b]) => a.localeCompare(b)))]));

// Reads a JSON file, treating a missing file as "no data" without a check-then-use race.
function readJsonIfPresent(path, fallback) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (e) {
    if (e && e.code === "ENOENT") return fallback;
    throw e;
  }
}
const baseline = readJsonIfPresent(BASELINE_PATH, {});
const grew = [];
for (const [file, codes] of Object.entries(current)) {
  for (const [code, n] of Object.entries(codes)) {
    const was = baseline[file]?.[code] ?? 0;
    if (n > was) grew.push(`${file}: ${code} ${was} -> ${n}`);
  }
}

const totals = {};
for (const codes of Object.values(current)) for (const [c, n] of Object.entries(codes)) totals[c] = (totals[c] ?? 0) + n;

function writeDoc(data) {
  const t = {};
  for (const codes of Object.values(data)) for (const [c, n] of Object.entries(codes)) t[c] = (t[c] ?? 0) + n;
  const lines = [
    "# Design debt baseline",
    "",
    "Generated by `node tooling/design/check-debt.mjs --update`. Do not edit by hand. The list only shrinks:",
    "`check-debt.mjs` fails when any file gains violations of a rule or a new file appears. Fix a file, then run",
    "`--update` to lower the baseline. Rules live in `tooling/design/rules.mjs`; principles in",
    "`docs/design-system/ux-principles.md`.",
    "",
    "## Totals per rule",
    "",
    "| Rule | Violations |",
    "|---|---|",
    ...Object.entries(t).sort().map(([c, n]) => `| ${c} | ${n} |`),
    "",
    `Files with debt: ${Object.keys(data).length}`,
    "",
    "## Per file",
    "",
    "| File | Rule | Count |",
    "|---|---|---|",
    ...Object.entries(data).flatMap(([f, codes]) => Object.entries(codes).map(([c, n]) => `| \`${f}\` | ${c} | ${n} |`)),
    "",
  ];
  writeFileSync(join(root, "docs/plan/design-debt.md"), lines.join("\n"));
}

if (arg === "--init" || (arg === "--update" && grew.length === 0)) {
  writeFileSync(BASELINE_PATH, JSON.stringify(sorted(current), null, 2) + "\n");
  writeDoc(sorted(current));
  console.log(`baseline written: ${Object.keys(current).length} files`, totals);
  process.exit(0);
}
if (grew.length > 0) {
  console.error("Design debt grew (fix the new violations; do not raise the baseline):");
  for (const g of grew) console.error("  " + g);
  process.exit(1);
}
const shrank = Object.entries(baseline).some(([f, codes]) => Object.entries(codes).some(([c, n]) => (current[f]?.[c] ?? 0) < n));
console.log(`design debt OK: ${Object.keys(current).length} files`, totals, shrank ? "(debt shrank: run --update to lower the baseline)" : "");
