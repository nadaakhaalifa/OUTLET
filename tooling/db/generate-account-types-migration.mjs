#!/usr/bin/env node
// Generates packages/db/migrations/0011_ledger_account_types.sql from the domain
// chart of accounts (packages/domain/src/chart-of-accounts/accounts.ts).
//   node tooling/db/generate-account-types-migration.mjs          write the file
//   node tooling/db/generate-account-types-migration.mjs --check  exit 1 on drift
// The source is read as text (it is TypeScript with extensionless imports, so it
// cannot be imported by plain node). packages/db/src/ledger-account-types.test.ts
// compares the generated seed with the real ACCOUNT_TYPES object independently.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = join(root, 'packages/domain/src/chart-of-accounts/accounts.ts');
const TARGET = join(root, 'packages/db/migrations/0011_ledger_account_types.sql');

const OWNER_TO_PERSISTED = {
  platform: 'platform', psp: 'psp', courier: 'courier', bnpl_provider: 'bnpl_provider',
  bank: 'bank', seller: 'store', shopper: 'user',
};

// Types added after 0011 shipped. Each has its own forward migration (INSERT ... ON CONFLICT);
// 0011 is never rewritten, so the generator leaves them out of its output.
export const POST_0011_TYPES = ['creator_payable', 'creator_commission_expense'];

export const parseAccountTypes = (src) => {
  const start = src.indexOf('export const ACCOUNT_TYPES');
  if (start === -1) throw new Error('ACCOUNT_TYPES not found');
  const body = src.slice(start);
  const rows = [];
  const re = /^ {2}([a-z_]+): \{\n([\s\S]*?)\n {2}\},?$/gm;
  for (const m of body.matchAll(re)) {
    const block = m[2];
    const pick = (field) => {
      const r = new RegExp(`^\\s{4}${field}:\\s*(?:"([^"]*)"|(true|false)),?$`, 'm').exec(block);
      if (!r) throw new Error(`${m[1]}: field ${field} not found`);
      return r[1] ?? r[2];
    };
    const type = pick('type');
    if (type !== m[1]) throw new Error(`key ${m[1]} != type ${type}`);
    const owner = pick('owner');
    const persisted = OWNER_TO_PERSISTED[owner];
    if (!persisted) throw new Error(`${type}: unmapped owner ${owner}`);
    rows.push({
      code: type,
      category: pick('category'),
      normal_side: pick('normalBalance'),
      owner_type: persisted,
      in_spec_t4: pick('inSpecT4') === 'true',
      status: pick('status'),
    });
  }
  if (rows.length === 0) throw new Error('no account types parsed');
  return rows.filter((r) => !POST_0011_TYPES.includes(r.code));
};

export const render = (rows) => {
  const values = rows
    .map((r) => `  ('${r.code}', '${r.category}', '${r.normal_side}', '${r.owner_type}', ${r.in_spec_t4}, '${r.status}')`)
    .join(',\n');
  return `-- migration: 0011_ledger_account_types
-- phase: expand
--
-- GENERATED by tooling/db/generate-account-types-migration.mjs from
-- packages/domain/src/chart-of-accounts/accounts.ts (ACCOUNT_TYPES). Do not
-- edit by hand: a drift test fails when this seed differs from the domain
-- table. To change the chart, add a NEW migration with INSERT ... ON CONFLICT.
--
-- ledger_accounts.type becomes a foreign key so a typo cannot create a new
-- account type (inconsistency I-08, ADR-0018). owner_type uses the persisted
-- vocabulary (seller -> store, shopper -> user).
--
-- Expand-safe: new table, new constraint added NOT VALID (a catalog-only
-- change, no table scan under lock) and then VALIDATEd, which takes only a
-- SHARE UPDATE EXCLUSIVE lock. Fails closed if an existing row has an unknown
-- type.

CREATE TABLE ledger_account_types (
  code        text PRIMARY KEY CHECK (code ~ '^[a-z][a-z0-9_]*$'),
  category    text NOT NULL CHECK (category IN ('asset', 'liability', 'revenue', 'expense')),
  normal_side text NOT NULL CHECK (normal_side IN ('debit', 'credit')),
  owner_type  text NOT NULL CHECK (owner_type IN ('platform', 'store', 'user', 'psp', 'courier', 'bnpl_provider', 'bank')),
  in_spec_t4  boolean NOT NULL,
  status      text NOT NULL CHECK (status IN ('active', 'reserved')),
  created_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO ledger_account_types (code, category, normal_side, owner_type, in_spec_t4, status) VALUES
${values}
ON CONFLICT (code) DO NOTHING;

GRANT SELECT ON ledger_account_types TO app_user;

ALTER TABLE ledger_accounts
  ADD CONSTRAINT ledger_accounts_type_fk
  FOREIGN KEY (type) REFERENCES ledger_account_types (code) NOT VALID;

ALTER TABLE ledger_accounts VALIDATE CONSTRAINT ledger_accounts_type_fk;
`;
};

const main = () => {
  const out = render(parseAccountTypes(readFileSync(SOURCE, 'utf8')));
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(TARGET, 'utf8'); } catch { /* missing */ }
    if (current !== out) {
      console.error('0011_ledger_account_types.sql differs from ACCOUNT_TYPES. Regenerate before it is applied anywhere; after release, add a new migration instead.');
      process.exit(1);
    }
    console.log(`ok: ${TARGET} matches ACCOUNT_TYPES`);
    return;
  }
  writeFileSync(TARGET, out);
  console.log(`wrote ${TARGET}`);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
